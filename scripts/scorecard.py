"""Compute the accuracy scorecard from stored notes (no API calls) and write the hand-grade sample.

    python -m scripts.scorecard
"""
from __future__ import annotations

import json
import re

from earnings_desk import config

from earnings_desk.scorecard import OUT_DIR, claims_frame, compute, load_notes, write_hand_grade_sample


def main() -> None:
    notes = load_notes()
    res = compute(notes)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "results.json").write_text(json.dumps(res, indent=1, default=str) + "\n")
    claims_frame(notes).to_csv(OUT_DIR / "claims.csv", index=False)
    wrote = write_hand_grade_sample(claims_frame(notes))
    print(f"{res['company_quarters']} company-quarters, {res['claims']} claims; numeric verified "
          f"{res['numeric']['verified_pct']}%, quotes matched {res['quote']['match_pct']}%")
    for r in res["injection"]:
        print(f"  injected {r['error_type']}: {r['caught']}/{r['injected']} caught")
    print("hand-grade CSV", "written" if wrote else "kept (already has grades)")
    update_readme(res)


def update_readme(res: dict) -> None:
    inj = res["injection"]
    injected = sum(r["injected"] for r in inj)
    caught = sum(r["caught"] for r in inj)
    lines = [
        f"Measured on **{res['company_quarters']} company-quarters** ({len(res['tickers'])} tickers, {res['claims']} claims):",
        "",
        f"- **{res['numeric']['verified_pct']}%** of {res['numeric']['claims']} numeric claims verified against XBRL "
        f"({res['numeric']['mismatch_pct']}% mismatched).",
        f"- **{res['quote']['match_pct']}%** of {res['quote']['claims']} quotes matched the press release word for word.",
        f"- **{caught / injected:.1%}** of {injected} injected errors caught by the verifier "
        f"(" + ", ".join(f"{r['error_type']} {r['caught']}/{r['injected']}" for r in inj) + ").",
        "- Failures: " + (", ".join(f"{k} ({v})" for k, v in res["failures"].items()) or "none") + ".",
        "",
        "_Generated by `scripts/scorecard.py`; details on the Scorecard page._",
    ]
    path = config.ROOT / "README.md"
    text = path.read_text()
    new = re.sub(r"(<!-- SCORECARD:START -->\n).*?(<!-- SCORECARD:END -->)", lambda m: m.group(1) + "\n".join(lines) + "\n" + m.group(2),
                 text, flags=re.S)
    path.write_text(new)


if __name__ == "__main__":
    main()
